//! The binary's own vocabulary, as a document the checker can read.
//!
//! A repository that claims "every command is checked" needs the commands to be objects; a claim
//! that "every diagnostic code has an explanation" needs the codes to be objects.  Until they are,
//! a universal claim has no extent to range over and the checker says so (`E-SCOPE-UNBOUNDED`).
//!
//! The three lists are generated from the binary rather than written by hand: a hand-written list
//! is a snapshot of what somebody remembered, and the point of the whole exercise is that the
//! inventory cannot go stale without something failing.

use std::path::Path;

use super::registry;

/// Write or print the inventory.  `--fixtures` names the directory the golden suite pins; the
/// commands and the codes come from this build, so the document cannot describe an older one.
pub(crate) fn cmd_inventory(
    fixtures_dir: Option<&Path>,
    json: bool,
    out: Option<&str>,
) -> super::Outcome {
    let Some(fixtures_dir) = fixtures_dir else {
        println!("usage: tsare inventory --fixtures DIR [--json] [--write FILE]");
        return super::Outcome::Usage;
    };
    let text = match document(fixtures_dir) {
        Ok(text) => text,
        Err(error) => return super::fail(error),
    };
    if let Some(path) = out {
        return match std::fs::write(path, &text) {
            Ok(()) => {
                println!("inventory written to {path}");
                super::Outcome::Ok
            }
            Err(error) => super::fail(format!("{path}: {error}")),
        };
    }
    if json {
        let strings = |names: Vec<&str>| {
            crate::json::Json::Arr(
                names
                    .into_iter()
                    .map(|name| crate::json::Json::Str(name.to_string()))
                    .collect(),
            )
        };
        let mut commands: Vec<&str> = registry::COMMANDS.iter().map(|c| c.name).collect();
        commands.extend(registry::HIDDEN.iter().copied());
        let docs = match fixtures(fixtures_dir) {
            Ok(names) => names,
            Err(error) => return super::fail(error),
        };
        let value = crate::json::Json::Obj(vec![
            ("commands".to_string(), strings(commands)),
            (
                "codes".to_string(),
                strings(tsare_lang::explain::CODES.to_vec()),
            ),
            (
                "documents".to_string(),
                strings(docs.iter().map(String::as_str).collect()),
            ),
        ]);
        println!("{}", crate::json::serialize(&value));
        return super::Outcome::Ok;
    }
    print!("{text}");
    super::Outcome::Ok
}

/// A name that is a legal `.tsare` identifier, from an arbitrary string: uppercase, and a run of
/// anything that is not a letter or a digit becomes one underscore.
fn identifier(prefix: &str, name: &str) -> String {
    let mut out = String::from(prefix);
    let mut last_underscore = false;
    for character in name.chars() {
        if character.is_ascii_alphanumeric() {
            out.push(character.to_ascii_uppercase());
            last_underscore = false;
        } else if !last_underscore {
            out.push('_');
            last_underscore = true;
        }
    }
    while out.ends_with('_') {
        out.pop();
    }
    out
}

/// The six fixture documents the golden suite pins, by file name.
fn fixtures(dir: &Path) -> Result<Vec<String>, String> {
    let mut names: Vec<String> = std::fs::read_dir(dir)
        .map_err(|error| format!("{}: {error}", dir.display()))?
        .filter_map(|entry| entry.ok().map(|item| item.path()))
        .filter(|path| path.extension().map(|ext| ext == "tsare").unwrap_or(false))
        .filter_map(|path| {
            path.file_name()
                .map(|name| name.to_string_lossy().to_string())
        })
        .collect();
    names.sort();
    Ok(names)
}

/// The inventory, as a `.tsare` document.
pub fn document(fixtures_dir: &Path) -> Result<String, String> {
    let mut commands: Vec<&str> = registry::COMMANDS
        .iter()
        .map(|command| command.name)
        .chain(registry::HIDDEN.iter().copied())
        .collect();
    commands.sort();
    let mut codes: Vec<&str> = tsare_lang::explain::CODES.to_vec();
    codes.sort();
    let docs = fixtures(fixtures_dir)?;

    let mut text = String::from(
        "# --- inventory: generated by `tsare inventory`; do not edit by hand ---\n\
         #\n\
         # The extents three universal claims range over: the commands this build dispatches,\n\
         # the diagnostic codes it can print, and the documents the golden suite pins.\n",
    );

    let mut exposes = Vec::new();
    for name in &commands {
        exposes.push(identifier("F_CMD_", name));
    }
    text.push_str(&format!(
        "\nlayer L_COMMANDS {{\n  name: \"the commands this build dispatches\",\n  exposes: [{}]\n}}\n",
        exposes.join(", ")
    ));
    for name in &commands {
        text.push_str(&format!(
            "fact {} {{ claim: \"the build dispatches the command `{name}`\", evidence: tool(\"tsare --help\"), layer: L_COMMANDS }}\n",
            identifier("F_CMD_", name)
        ));
    }

    let mut exposes = Vec::new();
    for code in &codes {
        exposes.push(identifier("F_CODE_", code));
    }
    text.push_str(&format!(
        "\nlayer L_CODES {{\n  name: \"the diagnostic codes this build can print\",\n  exposes: [{}]\n}}\n",
        exposes.join(", ")
    ));
    for code in &codes {
        text.push_str(&format!(
            "fact {} {{ claim: \"the build can print {code}\", evidence: code(\"crates/tsare-lang/src/explain.rs\"), layer: L_CODES }}\n",
            identifier("F_CODE_", code)
        ));
    }

    let mut exposes = Vec::new();
    for name in &docs {
        exposes.push(identifier("F_DOC_", name));
    }
    text.push_str(&format!(
        "\nlayer L_GOLDENS {{\n  name: \"the documents the golden suite pins\",\n  exposes: [{}]\n}}\n",
        exposes.join(", ")
    ));
    for name in &docs {
        text.push_str(&format!(
            "fact {} {{ claim: \"the golden suite pins {name}\", evidence: doc(\"crates/tsare/tests/fixtures/{name}\"), layer: L_GOLDENS }}\n",
            identifier("F_DOC_", name)
        ));
    }

    text.push_str("# --- end inventory ---\n");
    Ok(text)
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn an_identifier_is_a_name_the_language_accepts() {
        assert_eq!(identifier("F_CMD_", "check-json"), "F_CMD_CHECK_JSON");
        assert_eq!(identifier("F_CODE_", "E-COLLAPSE"), "F_CODE_E_COLLAPSE");
        assert_eq!(identifier("F_DOC_", "hier.v2.tsare"), "F_DOC_HIER_V2_TSARE");
    }
}

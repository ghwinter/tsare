//! The field table: kind -> (field, type, required).  One entry per kind, in source order.

/// One field of a kind: its name, the type a value must have, and whether a declaration must
/// write it.
pub type Field = (&'static str, &'static str, bool);

/// The fields a kind accepts, in the order the checker reports missing ones.  A type string is a
/// shape name (`str`, `num`, `attrs`, `instrument`, `evidence`), an `enum:` list of permitted
/// words, or a `list:` / `ref:` form.  `None` means the kind itself is unknown, which is not the
/// same error as an unknown field of a known kind.
pub fn spec(kind: &str) -> Option<&'static [Field]> {
    Some(match kind {
        "fact" => &[
            ("claim", "str", true),
            ("evidence", "evidence", true),
            ("attrs", "attrs", false),
            ("confirmed_by", "str", false),
            ("scope", "str", false),
            ("over", "list:ref:any", false),
            ("confidence", "num", false),
            ("artifact", "str", false),
            ("out", "str", false),
            ("layer", "ref:layer", false),
            ("supersedes", "list:ref:any", false),
            ("because", "list:ref:any", false),
        ],
        "concept" => &[
            ("name", "str", true),
            ("params", "list:str", false),
            ("grounded_by", "list:ref:fact", true),
            ("against", "list:ref:fact", false),
            ("parent", "ref:concept", false),
            ("layer", "ref:layer", false),
            ("supersedes", "list:ref:any", false),
            ("because", "list:ref:any", false),
        ],
        "proposition" => &[
            ("statement", "str", true),
            ("uses", "list:ref:concept", false),
            ("from", "list:ref:any", false),
            ("over", "list:ref:any", false),
            ("by", "enum:deductive,inductive,abductive", false),
            ("status", "enum:asserted,open", false),
            ("confidence", "num", false),
            ("layer", "ref:layer", false),
            ("supersedes", "list:ref:any", false),
            ("because", "list:ref:any", false),
        ],
        "hypothesis" => &[
            ("assumes", "list:ref:any", true),
            ("predicts", "str", true),
            ("test", "str", false),
            ("rival", "ref:hypothesis", false),
            ("verdict", "enum:open,supported,refuted", false),
            ("verdict_by", "ref:fact", false),
            ("layer", "ref:layer", false),
            ("supersedes", "list:ref:any", false),
            ("because", "list:ref:any", false),
        ],
        "question" => &[
            ("asks", "str", true),
            ("answers", "list:str", true),
            ("separates", "list:ref:hypothesis", true),
            ("to", "enum:user,tool,experiment", false),
            ("layer", "ref:layer", false),
            ("supersedes", "list:ref:any", false),
            ("because", "list:ref:any", false),
        ],
        "blindspot" => &[
            ("cannot_express", "str", true),
            ("witness", "list:ref:any", true),
            ("signature", "list:ref:concept", true),
            ("closes_with", "list:ref:question", false),
            ("layer", "ref:layer", false),
            ("supersedes", "list:ref:any", false),
            ("because", "list:ref:any", false),
        ],
        "warrant" => &[
            ("claim", "str", true),
            ("from", "list:ref:any", true),
            ("to", "ref:proposition", false),
            ("concludes", "rec:any", false),
            ("basis", "list:ref:any", false),
            ("attacks", "list:ref:warrant", false),
            ("confidence", "num", false),
            ("layer", "ref:layer", false),
            ("supersedes", "list:ref:any", false),
            ("because", "list:ref:any", false),
        ],
        "layer" => &[
            ("name", "str", true),
            ("exposes", "list:ref:any", true),
            ("supersedes", "list:ref:any", false),
            ("because", "list:ref:any", false),
        ],
        "law" => &[
            ("statement", "str", true),
            ("holds_in", "ref:layer", true),
            ("checked_by", "list:ref:any", false),
            ("refines", "ref:layer", false),
            ("requires", "list:str", false),
            ("layer", "ref:layer", false),
            ("supersedes", "list:ref:any", false),
            ("because", "list:ref:any", false),
        ],
        "value" => &[
            ("metric", "str", true),
            ("direction", "enum:min,max", true),
            ("unit", "str", false),
            ("threshold", "num", false),
            ("priority", "num", false),
            ("measured_by", "instrument", false),
            ("layer", "ref:layer", false),
            ("supersedes", "list:ref:any", false),
            ("because", "list:ref:any", false),
        ],
        "partition" => &[
            ("of", "ref:any", false),
            ("dimension", "ref:concept", false),
            ("elements", "list:ref:any", true),
            ("closure", "enum:closed,open,unknown", true),
            ("basis", "list:ref:any", false),
            ("closes_with", "list:ref:question", false),
            ("layer", "ref:layer", false),
            ("supersedes", "list:ref:any", false),
            ("because", "list:ref:any", false),
        ],
        "note" => &[
            ("tag", "enum:intuition,conjecture,preference,hunch", true),
            ("text", "str", true),
            ("about", "list:ref:any", false),
            ("layer", "ref:layer", false),
            ("supersedes", "list:ref:any", false),
            ("because", "list:ref:any", false),
        ],
        _ => return None,
    })
}
